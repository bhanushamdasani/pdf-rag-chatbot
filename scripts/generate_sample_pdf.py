"""Generates a professional 3-page sample PDF report for demonstration and testing."""

import os
import io
import pdfplumber

def generate_enterprise_pdf(output_path: str = "sample_docs/Enterprise_AI_Report_2025.pdf") -> bytes:
    """Builds a valid 3-page PDF document with realistic business and technical content."""
    pages_text = [
        [
            "Executive Summary: Enterprise AI and RAG Architecture Report 2025",
            "",
            "1. Overview and Market Dynamics",
            "In 2025, enterprise adoption of Retrieval-Augmented Generation (RAG) reached an all-time high.",
            "Over 78 percent of surveyed organizations reported integrating internal vector knowledge bases.",
            "Without grounded retrieval, baseline Large Language Models exhibited a hallucination rate of 28.4 percent.",
            "Implementing grounded RAG pipelines with strict citation constraints reduced hallucination to under 1.8 percent.",
            "",
            "2. Strategic Goals and Funding",
            "The primary initiative, codenamed Project Titan, aims to automate enterprise document intelligence.",
            "The target completion date is Q4 2025 with an allocated research grant of 15.5 million dollars.",
            "Key stakeholders include engineering, security governance, and customer support divisions."
        ],
        [
            "Section 2: Performance Benchmarks and Cost Analysis",
            "",
            "1. Infrastructure and Latency Benchmarks",
            "Vector search using FAISS with L2 index achieved an average retrieval latency of 14.2 milliseconds.",
            "In contrast, dense vector search across unindexed clusters required over 240 milliseconds.",
            "The end-to-end question-answering pipeline using Google Gemini 1.5 Flash averaged 820ms response time.",
            "",
            "2. Financial ROI and Efficiency Gains",
            "Enterprise infrastructure costs decreased by 62 percent after migrating from self-hosted LLMs to Gemini API.",
            "Total verified annual cost savings reached 4.6 million dollars across all operating units.",
            "Support resolution time dropped from 45 minutes per ticket to 3.5 minutes per ticket using automated RAG."
        ],
        [
            "Section 3: Security, Governance and Source Verification",
            "",
            "1. Compliance Standards",
            "The RAG system complies with SOC2 Type II, ISO 27001, HIPAA, and GDPR data residency standards.",
            "No proprietary user data or PDF content is retained for external model retraining.",
            "",
            "2. Auditability and Verifiable Citations",
            "All responses generated by the conversational chain must cite original source page numbers.",
            "Conversational memory uses a sliding window of 5 turns to prevent context window overflow.",
            "In case of conflicting data, the retriever defaults to the highest semantic similarity score."
        ]
    ]

    num_pages = len(pages_text)
    page_obj_ids = [3 + i for i in range(num_pages)]
    font_id = 3 + num_pages
    stream_obj_ids = [font_id + 1 + i for i in range(num_pages)]

    # Catalog & Pages
    catalog = b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
    kids_str = " ".join(f"{pid} 0 R" for pid in page_obj_ids)
    pages = f"2 0 obj\n<< /Type /Pages /Kids [{kids_str}] /Count {num_pages} >>\nendobj\n".encode("latin-1")

    page_objs = []
    for pid, sid in zip(page_obj_ids, stream_obj_ids):
        p = f"{pid} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 {font_id} 0 R >> >> /Contents {sid} 0 R >>\nendobj\n".encode("latin-1")
        page_objs.append(p)

    font_obj = f"{font_id} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n".encode("latin-1")

    stream_objs = []
    for sid, lines in zip(stream_obj_ids, pages_text):
        commands = ["BT", "/F1 12 Tf", "50 740 Td", "16 TL"]
        for line in lines:
            safe = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            if safe.startswith("Executive") or safe.startswith("Section"):
                commands.append(f"T* /F1 16 Tf ({safe}) Tj /F1 12 Tf")
            elif safe.startswith("1.") or safe.startswith("2."):
                commands.append(f"T* /F1 13 Tf ({safe}) Tj /F1 12 Tf")
            else:
                commands.append(f"T* ({safe}) Tj")
        commands.append("ET")
        stream_content = "\n".join(commands).encode("latin-1")
        st_obj = f"{sid} 0 obj\n<< /Length {len(stream_content)} >>\nstream\n".encode("latin-1") + stream_content + b"\nendstream\nendobj\n"
        stream_objs.append(st_obj)

    all_objs = [catalog, pages] + page_objs + [font_obj] + stream_objs

    out = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for obj in all_objs:
        offsets.append(len(out))
        out.extend(obj)

    xref_offset = len(out)
    out.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode("latin-1"))
    for off in offsets[1:]:
        out.extend(f"{off:010d} 00000 n \n".encode("latin-1"))

    out.extend(f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n".encode("latin-1"))
    raw_pdf = bytes(out)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "wb") as f:
        f.write(raw_pdf)

    return raw_pdf

if __name__ == "__main__":
    generate_enterprise_pdf()
    print("Generated sample PDF report at sample_docs/Enterprise_AI_Report_2025.pdf")
